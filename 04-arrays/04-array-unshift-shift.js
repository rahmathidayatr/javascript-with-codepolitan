// Problem 1: Add an item to the start of an array with unshift()
let fruits = ["Mango", "Orange"];
fruits.unshift("Apple")
console.log(fruits)

// Problem 2: Remove the first item with shift()
let foods = ["Nasi Goreng", "Mie Goreng", "Sate"];
foods.shift()
console.log(foods)

// Problem 3: Combine unshift(), push(), shift(), and pop()
let animals = ["Dog", "Rabbit"];
animals.unshift('Cat')
animals.push('Hamster')
animals.shift()
animals.pop()
console.log(animals)