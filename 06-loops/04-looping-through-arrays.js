// Problem 1: Loop through an array with a for loop
let colors = ["Red", "Blue", "Green"];
for (let i = 0; i < colors.length; i++){
    console.log(colors[i])
}

// Problem 2: Loop through a numeric array
let numbers = [5, 10, 15, 20];
for (let i = 0; i < numbers.length; i++){
    console.log(numbers[i])
}

// Problem 3: Loop through an array and transform each value
let moreNumbers = [2, 4, 6, 8];
