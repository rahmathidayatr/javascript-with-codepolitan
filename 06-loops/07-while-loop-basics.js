// Problem 1: Count up with a while loop
let i = 1
while (i <= 5){
    console.log(i)
    i++
}

// Problem 2: Count down with a while loop
let j = 5;
while (j >= 1){
    console.log(j)
    j--
}

// Problem 3: Loop through an array with a while loop
let fruits = ["Apple", "Mango", "Orange", "Banana"];
let k = 0
while (k < fruits.length){
    console.log(fruits[k])
    k++
}