// Problem 1: Choose a menu item with a switch statement
let choice = 1;

switch (choice) {
    case 1:
        console.log("Nasi Goreng")
        break
    case 2:
        console.log("Mie Goreng")
        break
    case 3:
        console.log("Ayam Goreng")
        break
    default:
        console.log("Menu not available")
}

// Problem 2: Get the day name with a switch statement
let day = 5;
switch (day) {
    case 1:
        console.log("Monday")
        break
    case 2:
        console.log("Tuesday")
        break
    case 3:
        console.log("Wednesday")
        break
    case 4:
        console.log("Thursday")
        break
    case 5:
        console.log("Friday")
        break
    default:
        console.log("Invalid day")
}

// Problem 3: Get a grade description with a switch statement
let grade = "B";
switch (grade) {
    case "A":
        console.log('Excellent')
        break
    case "B":
        console.log('Good')
        break
    case "C":
        console.log('Fair')
        break
    case "D":
        console.log('Poor')
        break
    default:
        console.log('Invalid grade')
}