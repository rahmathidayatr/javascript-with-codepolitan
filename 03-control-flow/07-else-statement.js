// Problem 1: Use if...else to check legal age
let age = 20
if (age >= 18){
    console.log("Adult")
} else {
    console.log("Not an adult yet")
}

// Problem 2: Use if...else to check account balance
let balance = 50000
if (balance >= 100000){
    console.log("Sufficient balance")
} else {
    console.log("Insufficient balance")
}

// Problem 3: Use if...else if...else to assign a letter grade
let score = 65
if (score >= 80) {
    console.log("A")
} else if (score >= 70) {
    console.log("B")
} else {
    console.log("C")
}